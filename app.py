# app.py

# Import the compiled LangGraph workflow
from graph.workflow import build_graph

# Import LangChain message types
from langchain_core.messages import HumanMessage, AIMessage

# Rich library imports for a better CLI interface
from rich.console import Console
from rich.panel import Panel
from rich.prompt import Prompt
from rich.rule import Rule

# Initialize console and graph
console = Console()
graph = build_graph()

# Clear terminal and display application header
console.clear()
console.print(
    Rule(
        "🌐 LANGGRAPH ENTERPRISE SUPPORT PIPELINE",
        style="bold double blue"
    )
)

# Session ID enables persistent memory across conversations
session_input = Prompt.ask(
    "\n🔑 Enter Session ID",
    default="1"
)

# LangGraph configuration object
config = {
    "configurable": {
        "thread_id": session_input.strip()
    }
}

# Main conversation loop
while True:

    # Accept user query
    query = Prompt.ask("\n[bold cyan]👤 You[/bold cyan]")

    # Exit condition
    if query.lower() == "quit":
        break

    # Ignore empty inputs
    if not query.strip():
        continue

    # Send user message into LangGraph workflow
    result = graph.invoke(
        {"messages": [HumanMessage(content=query)]},
        config=config
    )

    # Retrieve current graph state
    state_snapshot = graph.get_state(config)

    # Extract state variables used for routing and tracing
    kb_context = state_snapshot.values.get("kb_context", "")
    query_category = state_snapshot.values.get("query_category", "")

    # ---------------------------------------------------------
    # HUMAN-IN-THE-LOOP (HITL) CHECKPOINT
    # ---------------------------------------------------------
    # If the graph pauses at the human approval node,
    # manual approval/rejection is required before continuing.
    # ---------------------------------------------------------
    if state_snapshot.next and "human_checkpoint" in state_snapshot.next:

        # Draft response generated by the agent
        polished_draft = state_snapshot.values.get(
            "agent_draft_response",
            ""
        )

        # Display warning panel
        console.print("\n")
        console.print(
            Panel(
                (
                    "[bold yellow]The system generated a "
                    "sensitive reply that requires manual "
                    "validation.[/bold yellow]\n"
                ),
                title="🛑🕵️ HUMAN-IN-THE-LOOP INTERVENTION CRITICAL",
                border_style="red"
            )
        )

        # Ask reviewer for approval decision
        decision = Prompt.ask(
            "🔒 Approve this sensitive transaction?",
            choices=["yes", "no"],
            default="yes"
        ).strip().lower()

        # -----------------------------------------------------
        # APPROVAL FLOW
        # -----------------------------------------------------
        if decision == "yes":

            console.print(
                "✅ [bold green]Approved.[/bold green] "
                "Informing Supervisor to release the resolution..."
            )

            # Update graph state and resume execution
            graph.update_state(
                config,
                {
                    "human_feedback": "approved",
                    "requires_approval": False,
                    "query_category": "supervisor"
                },
                as_node="human_checkpoint"
            )

            # Resume workflow execution
            result = graph.invoke(None, config=config)

        # -----------------------------------------------------
        # REJECTION FLOW
        # -----------------------------------------------------
        else:

            # Collect rejection reason
            reason = Prompt.ask(
                "📝 [bold red]Rejected.[/bold red] "
                "Enter the mandatory reason for denial"
            )

            console.print(
                "🔄 [bold yellow]Passing reason to "
                "Supervisor for a professional rejection "
                "rewrite...[/bold yellow]"
            )

            # Update graph state with rejection feedback
            graph.update_state(
                config,
                {
                    "human_feedback":
                        reason if reason.strip()
                        else "Policy restrictions.",
                    "requires_approval": False,
                    "query_category": "supervisor"
                },
                as_node="human_checkpoint"
            )

            # Resume workflow execution
            result = graph.invoke(None, config=config)

    # ---------------------------------------------------------
    # STANDARD WORKFLOW PATH
    # ---------------------------------------------------------
    else:

        # Retrieve conversation messages from state
        messages = state_snapshot.values.get("messages", [])

        # If memory agent generated the final answer,
        # display the committed response
        if (
            query_category == "memory_recall"
            and messages
            and not state_snapshot.values.get("agent_draft_response")
        ):

            final_msg = messages[-1].content

            console.print(
                Panel(
                    f"[bold white]{final_msg}[/bold white]",
                    title="✨ Response Commit",
                    border_style="green",
                    expand=False
                )
            )